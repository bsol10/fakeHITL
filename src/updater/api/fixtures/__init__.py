"""Fixture data for the API, extracted from the approved prototype.

Generated by ``scripts/extract_prototype_fixtures.py``. Regenerate rather than
editing the JSON by hand, so the test suite notices if the fixtures and the
prototype drift apart.
"""

from __future__ import annotations

import json
from importlib.resources import files
from typing import Any

__all__ = ["load"]


def load(name: str) -> Any:
    """The parsed content of one fixture file, e.g. ``load("claims.json")``."""
    return json.loads(files(__name__).joinpath(name).read_text(encoding="utf-8"))
