"""Fixture data for the phase 0 mock API, extracted from the approved prototype.

Generated by ``scripts/extract_prototype_fixtures.py``; do not edit the JSON by
hand. Regenerate it instead, so the fixtures and the prototype cannot drift
apart without the test suite noticing.
"""

from __future__ import annotations

import json
from importlib.resources import files
from typing import Any

__all__ = ["load"]


def load(name: str) -> Any:
    """The parsed content of one fixture file, e.g. ``load("claims.json")``."""
    return json.loads(files(__name__).joinpath(name).read_text(encoding="utf-8"))
